import { describe, expect, expectTypeOf, it, vi } from "vitest"
import { createAlertStore } from "./index.js"
describe("alert store", () => {
  it("keeps a new subscription when an old unsubscribe is called twice", () => {
    const store = createAlertStore()
    const stop = store.subscribe(() => undefined)
    stop()
    const listener = vi.fn<() => void>()
    store.subscribe(listener)
    stop()
    store.add({ title: "Notice" })
    expect(listener).toHaveBeenCalledOnce()
  })
  it("isolates regions and instances with stable immutable snapshots", () => {
    const store = createAlertStore()
    const listener = vi.fn<() => void>()
    const other = vi.fn<() => void>()
    const stop = store.subscribe(listener)
    store.subscribe(other, "panel")
    const empty = store.getSnapshot()
    expect(store.getSnapshot()).toBe(empty)
    const handle = store.add({ title: "Original" })
    const snapshot = store.getSnapshot()
    handle.update({ title: "Updated" })
    expect(snapshot[0]?.title).toBe("Original")
    expect(Object.isFrozen(snapshot[0])).toBe(true)
    expect(store.getSnapshot()[0]?.title).toBe("Updated")
    expect(listener).toHaveBeenCalledTimes(2)
    expect(other).not.toHaveBeenCalled()
    expect(createAlertStore().getSnapshot()).toEqual([])
    expect(store.getServerSnapshot()).toBe(empty)
    stop()
    handle.dismiss()
    expect(store.getSnapshot()).toBe(empty)
    expect(listener).toHaveBeenCalledTimes(2)
  })
  it("replaces in place, scopes ids, and invalidates stale handles", () => {
    const store = createAlertStore()
    const dismissed = vi.fn<() => void>()
    const old = store.add({ id: "same", title: "Old", onDismiss: dismissed })
    store.add({ id: "last" })
    const replacement = store.add({ id: "same", title: "New" })
    old.update({ title: "Stale" })
    old.dismiss()
    expect(old.isActive).toBe(false)
    expect(replacement.isActive).toBe(true)
    expect(store.getSnapshot().map((entry) => entry.id)).toEqual(["same", "last"])
    expect(store.getSnapshot()[0]?.title).toBe("New")
    store.add({ id: "same" }, "panel")
    replacement.dismiss()
    expect(store.isActive("same")).toBe(false)
    expect(store.isActive("same", "panel")).toBe(true)
    expect(dismissed).not.toHaveBeenCalled()
    store.update("missing", {})
    store.dismiss("missing")
  })
  it("avoids generated-id collisions and supplies intent defaults", () => {
    const store = createAlertStore()
    store.add({ id: "alert-2" })
    expect(store.add({}).id).not.toBe("alert-2")
    for (const intent of ["info", "success", "warning", "error"] as const) {
      store[intent]({ title: intent })
    }
    expect(
      store
        .getSnapshot()
        .slice(2)
        .map((entry) => entry.intent)
    ).toEqual(["info", "success", "warning", "error"])
    expect(store.getSnapshot()[0]?.dismissible).toBe(true)
  })
  it("dismisses once, flushes silently, and tolerates reentrant callbacks", () => {
    const store = createAlertStore()
    const onDismiss = vi.fn<() => void>(() => {
      store.add({ title: "Added by callback" })
    })
    const handle = store.add({ onDismiss })
    handle.dismiss()
    handle.dismiss()
    expect(onDismiss).toHaveBeenCalledTimes(1)
    const silent = vi.fn<() => void>()
    store.add({ onDismiss: silent }, "panel")
    store.flush()
    expect(store.getSnapshot()).toEqual([])
    expect(store.getSnapshot("panel")).toEqual([])
    expect(silent).not.toHaveBeenCalled()
    store.dismissAll()
  })
  it("finishes notification and dismissal callbacks even if one throws", () => {
    const store = createAlertStore()
    const first = vi.fn<() => void>(() => {
      throw new Error("handler failed")
    })
    const second = vi.fn<() => void>()
    store.add({ onDismiss: first })
    store.add({ onDismiss: second })
    const subscriber = vi.fn<() => void>()
    store.subscribe(() => {
      throw new Error("subscriber failed")
    })
    store.subscribe(subscriber)
    expect(() => store.dismissAll()).toThrow(AggregateError)
    expect(store.getSnapshot()).toEqual([])
    expect(first).toHaveBeenCalledOnce()
    expect(second).toHaveBeenCalledOnce()
    expect(subscriber).toHaveBeenCalledOnce()
  })
  it("disposes silently and rejects new entries without dropping teardown notifications", () => {
    const store = createAlertStore()
    const callback = vi.fn<() => void>()
    store.add({ onDismiss: callback })
    const listener = vi.fn<() => void>()
    store.subscribe(listener)
    store.dispose()
    store.dispose()
    expect(listener).toHaveBeenCalledOnce()
    expect(callback).not.toHaveBeenCalled()
    expect(() => store.add({})).toThrow("disposed")
    store.subscribe(listener)()
    store.flush()
    expect(listener).toHaveBeenCalledOnce()
  })
  it("supports typed payloads and clears actions without mutating caller data", () => {
    const store = createAlertStore<{ message: string }>()
    const action = { label: { message: "Undo" }, onClick: vi.fn<() => void>() }
    const h = store.add({ title: { message: "Saved" }, action })
    expectTypeOf(store.getSnapshot()[0]?.title).toEqualTypeOf<{ message: string } | undefined>()
    action.onClick = vi.fn<() => void>()
    expect(store.getSnapshot()[0]?.action?.onClick).not.toBe(action.onClick)
    h.update({ action: undefined, dismissible: false })
    expect(store.getSnapshot()[0]?.action).toBeUndefined()
    expect(store.getSnapshot()[0]?.dismissible).toBe(false)
  })
})
