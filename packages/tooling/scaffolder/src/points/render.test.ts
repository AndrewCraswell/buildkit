import { describe, expect, it } from "vitest"
import { z } from "zod"
import { definePoint } from "../manifest/define.js"
import { PlanError } from "../plan/errors.js"
import { applyFixture, initRequest } from "../testing/fixture.js"
import { renderPoints, type PointEntry } from "./render.js"

const list = definePoint({
  id: "vite.plugins",
  version: 1,
  kind: "list",
  file: "src/generated/x/config.ts",
  export: "vitePlugins"
})

function entry(id: string, extra: Partial<PointEntry> = {}): PointEntry {
  return {
    point: "vite.plugins",
    id,
    contributor: "@x/a",
    value: { call: { module: "plugin-" + id, export: id } },
    ...extra
  }
}

function render(points = [list], entries: PointEntry[] = []) {
  return renderPoints({ points: points.map((definition) => ({ definition, owner: "target" })), entries, product: "x" })
}

function failure(run: () => unknown): PlanError {
  try {
    run()
  } catch (error) {
    if (error instanceof PlanError) {
      return error
    }
    throw error
  }
  throw new Error("expected a PlanError")
}

describe("renderPoints", () => {
  it("renders every point even with no entries, with a header naming its contributors", () => {
    const { files } = render()
    expect(files.get("src/generated/x/config.ts")?.content).toBe(
      [
        "// Generated by x from target. Don't edit this file:",
        "// run `x add` or `x config` to change it, or override an entry in your own code.",
        "",
        "/** Entries of vite.plugins by id, for overriding one. */",
        "export const vitePluginsById = {}",
        "/** vite.plugins (list, contract v1). */",
        "export const vitePlugins = {",
        "  pre: [],",
        "  framework: [],",
        "  post: [],",
        "}",
        ""
      ].join("\n")
    )
  })

  it("orders by band, then before and after, then id, and exports entries by id for overrides", () => {
    const { files } = render(
      [list],
      [
        entry("b"),
        entry("a", { order: { after: ["@x/a/b"] } }),
        entry("first", { order: { band: "pre" } }),
        entry("c", { order: { before: ["@x/a/b"] } }),
        entry("last", { order: { band: "post" } })
      ]
    )
    const content = files.get("src/generated/x/config.ts")?.content ?? ""
    expect(content).toContain(
      '  framework: [vitePluginsById["@x/a/c"], vitePluginsById["@x/a/b"], vitePluginsById["@x/a/a"]],'
    )
    expect(content).toContain('  pre: [vitePluginsById["@x/a/first"]],')
    expect(content).toContain('"@x/a/last": last(),')
    expect(content).toContain('import { a } from "plugin-a"')
  })

  it("a cycle in ordering is a plan error", () => {
    expect(
      failure(() =>
        render([list], [entry("a", { order: { after: ["@x/a/b"] } }), entry("b", { order: { after: ["@x/a/a"] } })])
      ).code
    ).toBe("E_CYCLE")
  })

  it("renders refs, calls with JSON arguments and values, deduplicating and aliasing imports", () => {
    const map = definePoint({
      id: "env.schema",
      version: 2,
      kind: "map",
      file: "src/generated/x/server.ts",
      export: "envSchema",
      payload: z.object({ type: z.string() })
    })
    const single = definePoint({
      id: "router.rewrite",
      version: 1,
      kind: "single",
      file: "src/generated/x/server.ts",
      export: "rewrite"
    })
    const { files } = render(
      [map, single],
      [
        { point: "env.schema", id: "API_URL", contributor: "@x/a", value: { value: { type: "url" } } },
        {
          point: "router.rewrite",
          id: "locale",
          contributor: "@x/b",
          value: { call: { module: "./src/i18n/rewrite", export: "rewrite", args: [{ prefix: true }] } }
        }
      ]
    )
    const content = files.get("src/generated/x/server.ts")?.content ?? ""
    expect(content).toContain('import { rewrite as rewrite_2 } from "../../i18n/rewrite"')
    expect(content).toContain('  "API_URL": {"type":"url"},')
    expect(content).toContain('export const rewrite = rewrite_2({"prefix":true})')
    expect(files.get("src/generated/x/server.ts")?.contributors).toEqual(["@x/a", "@x/b", "target"])
    const defaults = render([list], [entry("d", { value: { ref: { module: "@scope/my-plugin", export: "default" } } })])
    expect(defaults.files.get("src/generated/x/config.ts")?.content).toContain(
      'import myPlugin from "@scope/my-plugin"'
    )
  })

  it("skips if-present entries for absent points, and errors for required ones", () => {
    const skipped = render([], [entry("a", { point: "nowhere", when: "if-present" })])
    expect(skipped.notices).toEqual([
      { code: "entry-skipped", text: "@x/a skipped nowhere, because nothing selected defines it." }
    ])
    expect(failure(() => render([], [entry("a", { point: "nowhere" })])).message).toContain(
      "nothing selected defines that point"
    )
  })

  it("refuses duplicate points, entries, keys and single entries, and bad payloads or names", () => {
    expect(failure(() => render([list, list])).message).toContain("defined by both")
    expect(failure(() => render([list], [entry("a"), entry("a")])).message).toContain("more than once")
    const single = definePoint({ id: "one", version: 1, kind: "single", file: "a.ts", export: "one" })
    expect(
      failure(() => render([single], [entry("a", { point: "one" }), entry("b", { point: "one", contributor: "@x/b" })]))
        .message
    ).toContain("takes one entry")
    const map = definePoint({ id: "map", version: 1, kind: "map", file: "a.ts", export: "map", payload: z.string() })
    expect(
      failure(() =>
        render(
          [map],
          [
            entry("K", { point: "map", value: { value: "a" } }),
            entry("K", { point: "map", contributor: "@x/b", value: { value: "b" } })
          ]
        )
      ).message
    ).toContain("set by both")
    expect(failure(() => render([map], [entry("K", { point: "map", value: { value: 1 } })])).message).toContain(
      "doesn't match the payload"
    )
    expect(failure(() => render([{ ...list, export: "not valid" }])).message).toContain("isn't a valid name")
    expect(
      failure(() => render([list], [entry("a", { value: { ref: { module: "x", export: "no-dash" } } })])).message
    ).toContain("isn't a valid export name")
  })

  it("is wired at init: generated files exist and the target's seeds import them", async () => {
    const files = await applyFixture({}, initRequest({ optional: ["@fixture/i18n"] }))
    expect(files["src/generated/fixture/client.ts"]).toContain('import { I18nProvider } from "../../i18n/setup"')
    expect(files["vite.config.ts"]).toContain("./src/generated/fixture/config")
    expect(files["src/generated/fixture/server.ts"]).toContain('"DATABASE_URL": {"type":"string"}')
  })
})
