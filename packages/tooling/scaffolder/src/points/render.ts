import type { Band, EntryValue, Order, PointDefinition } from "../manifest/types.js"
import { PlanError } from "../plan/errors.js"
import { relativeModule } from "../plan/paths.js"
import type { Notice } from "../plan/types.js"

export interface OwnedPoint {
  definition: PointDefinition
  /** The target or add-on that defines and renders the point. */
  owner: string
}

export interface PointEntry {
  point: string
  /** The entry's own id. Its full id is `<contributor>/<id>`. */
  id: string
  value: EntryValue
  order?: Order
  when?: "required" | "if-present"
  contributor: string
}

export interface RenderedPointFile {
  content: string
  contributors: string[]
}

const bands: Band[] = ["pre", "framework", "post"]
const identifier = /^[A-Za-z_$][\w$]*$/

/**
 * Renders every point into its generated TypeScript file. Each point is rendered even with no entries, so a target's
 * wiring can import it from the first `init`.
 */
export function renderPoints(input: { points: OwnedPoint[]; entries: PointEntry[]; product: string }): {
  files: Map<string, RenderedPointFile>
  notices: Notice[]
} {
  const notices: Notice[] = []
  const points = new Map<string, OwnedPoint>()
  for (const point of input.points) {
    const existing = points.get(point.definition.id)
    if (existing) {
      throw new PlanError(
        "E_CONTRIBUTION",
        `Point ${point.definition.id} is defined by both ${existing.owner} and ${point.owner}.`
      )
    }
    if (!identifier.test(point.definition.export)) {
      throw new PlanError(
        "E_CONTRIBUTION",
        `Point ${point.definition.id} exports "${point.definition.export}", which isn't a valid name.`
      )
    }
    points.set(point.definition.id, point)
  }
  const byPoint = new Map<string, (PointEntry & { fullId: string })[]>()
  const fullIds = new Set<string>()
  for (const entry of input.entries) {
    const point = points.get(entry.point)
    if (!point) {
      if (entry.when === "if-present") {
        notices.push({
          code: "entry-skipped",
          text: `${entry.contributor} skipped ${entry.point}, because nothing selected defines it.`
        })
        continue
      }
      throw new PlanError(
        "E_CONTRIBUTION",
        `${entry.contributor} contributes to ${entry.point}, but nothing selected defines that point.`
      )
    }
    const fullId = `${entry.contributor}/${entry.id}`
    if (fullIds.has(fullId)) {
      throw new PlanError("E_CONTRIBUTION", `${entry.contributor} contributes entry "${entry.id}" more than once.`)
    }
    fullIds.add(fullId)
    if ("value" in entry.value && point.definition.payload) {
      const parsed = point.definition.payload.safeParse(entry.value.value)
      if (!parsed.success) {
        throw new PlanError(
          "E_CONTRIBUTION",
          `${fullId} doesn't match the payload of ${entry.point}: ${parsed.error.issues.map((issue) => issue.message).join("; ")}.`
        )
      }
    }
    const list = byPoint.get(entry.point) ?? []
    list.push({ ...entry, fullId })
    byPoint.set(entry.point, list)
  }
  const byFile = new Map<string, OwnedPoint[]>()
  for (const point of points.values()) {
    const list = byFile.get(point.definition.file) ?? []
    list.push(point)
    byFile.set(point.definition.file, list)
  }
  const files = new Map<string, RenderedPointFile>()
  for (const [file, filePoints] of [...byFile].sort(([left], [right]) => compare(left, right))) {
    // Imports must not shadow the bindings the file exports.
    const imports = new ImportSet(
      file,
      filePoints.flatMap((point) => [point.definition.export, `${point.definition.export}ById`])
    )
    const sections: string[] = []
    const contributors = new Set<string>()
    for (const point of filePoints.sort((left, right) => compare(left.definition.id, right.definition.id))) {
      contributors.add(point.owner)
      const entries = orderEntries(point.definition, byPoint.get(point.definition.id) ?? [])
      entries.forEach((entry) => contributors.add(entry.contributor))
      sections.push(renderPoint(point.definition, entries, imports))
    }
    const names = [...contributors].sort(compare)
    const header = [
      `// Generated by ${input.product} from ${names.join(", ")}. Don't edit this file:`,
      `// run \`${input.product} add\` or \`${input.product} config\` to change it, or override an entry in your own code.`
    ]
    const importLines = imports.render()
    const content = [
      ...header,
      "",
      ...(importLines.length > 0 ? [...importLines, ""] : []),
      sections.join("\n\n"),
      ""
    ].join("\n")
    files.set(file, { content, contributors: names })
  }
  return { files, notices }
}

function renderPoint(
  definition: PointDefinition,
  entries: (PointEntry & { fullId: string })[],
  imports: ImportSet
): string {
  const name = definition.export
  const doc = `/** ${definition.title ?? definition.id} (${definition.kind}, contract v${definition.version}). */`
  if (definition.kind === "single") {
    const [only, second] = entries
    if (second && only) {
      throw new PlanError(
        "E_CONTRIBUTION",
        `${definition.id} takes one entry, but ${only.contributor} and ${second.contributor} both contribute.`
      )
    }
    return `${doc}\nexport const ${name} = ${only ? renderValue(only.value, imports) : "undefined"}`
  }
  if (definition.kind === "map") {
    const keys = new Map<string, string>()
    for (const entry of entries) {
      const owner = keys.get(entry.id)
      if (owner) {
        throw new PlanError(
          "E_CONTRIBUTION",
          `${definition.id} key "${entry.id}" is set by both ${owner} and ${entry.contributor}.`
        )
      }
      keys.set(entry.id, entry.contributor)
    }
    const lines = entries.map((entry) => `  ${JSON.stringify(entry.id)}: ${renderValue(entry.value, imports)},`)
    return `${doc}\nexport const ${name} = {${lines.length > 0 ? `\n${lines.join("\n")}\n` : ""}}`
  }
  const byId = entries.map((entry) => `  ${JSON.stringify(entry.fullId)}: ${renderValue(entry.value, imports)},`)
  const banded = bands.map((band) => {
    const refs = entries
      .filter((entry) => (entry.order?.band ?? "framework") === band)
      .map((entry) => `${name}ById[${JSON.stringify(entry.fullId)}]`)
    return `  ${band}: [${refs.join(", ")}],`
  })
  return [
    `/** Entries of ${definition.id} by id, for overriding one. */`,
    `export const ${name}ById = {${byId.length > 0 ? `\n${byId.join("\n")}\n` : ""}}`,
    doc,
    `export const ${name} = {`,
    ...banded,
    "}"
  ].join("\n")
}

/** Bands first, then `before` and `after` within a band, then ids. A cycle is a plan error. */
function orderEntries<T extends PointEntry & { fullId: string }>(definition: PointDefinition, entries: T[]): T[] {
  const result: T[] = []
  for (const band of bands) {
    const inBand = entries.filter((entry) => (entry.order?.band ?? "framework") === band)
    const ids = new Set(inBand.map((entry) => entry.fullId))
    const requiredBefore = new Map<string, Set<string>>(inBand.map((entry) => [entry.fullId, new Set<string>()]))
    for (const entry of inBand) {
      for (const after of entry.order?.after ?? []) {
        if (ids.has(after)) {
          requiredBefore.get(entry.fullId)?.add(after)
        }
      }
      for (const before of entry.order?.before ?? []) {
        if (ids.has(before)) {
          requiredBefore.get(before)?.add(entry.fullId)
        }
      }
    }
    const pending = inBand.map((entry) => entry.fullId).sort(compare)
    const done = new Set<string>()
    while (pending.length > 0) {
      const index = pending.findIndex((id) =>
        [...(requiredBefore.get(id) ?? [])].every((dependency) => done.has(dependency))
      )
      const next = index === -1 ? undefined : pending[index]
      if (next === undefined) {
        throw new PlanError(
          "E_CYCLE",
          `Entries of ${definition.id} order each other in a cycle: ${pending.join(", ")}.`
        )
      }
      pending.splice(index, 1)
      done.add(next)
      const entry = inBand.find((candidate) => candidate.fullId === next)
      if (entry) {
        result.push(entry)
      }
    }
  }
  return result
}

function renderValue(value: EntryValue, imports: ImportSet): string {
  if ("ref" in value) {
    return imports.add(value.ref.module, value.ref.export)
  }
  if ("call" in value) {
    const args = (value.call.args ?? []).map((arg) => JSON.stringify(arg)).join(", ")
    return `${imports.add(value.call.module, value.call.export)}(${args})`
  }
  return JSON.stringify(value.value) ?? "undefined"
}

class ImportSet {
  readonly #file: string
  readonly #bindings = new Map<string, string>()
  readonly #used = new Set<string>()

  constructor(file: string, reserved: readonly string[]) {
    this.#file = file
    reserved.forEach((name) => this.#used.add(name))
  }

  add(module: string, exported: string): string {
    if (exported !== "default" && !identifier.test(exported)) {
      throw new PlanError("E_CONTRIBUTION", `"${exported}" from ${module} isn't a valid export name.`)
    }
    const specifier = module.startsWith("./") ? relativeModule(this.#file, module.slice(2)) : module
    const key = `${specifier}\u0000${exported}`
    const existing = this.#bindings.get(key)
    if (existing) {
      return existing
    }
    const base = exported === "default" ? camelCase(specifier) : exported
    let local = base
    for (let suffix = 2; this.#used.has(local); suffix++) {
      local = `${base}_${suffix}`
    }
    this.#used.add(local)
    this.#bindings.set(key, local)
    return local
  }

  render(): string[] {
    const byModule = new Map<string, { defaultName?: string; named: string[] }>()
    for (const [key, local] of this.#bindings) {
      const [specifier = "", exported = ""] = key.split("\u0000")
      const entry = byModule.get(specifier) ?? { named: [] }
      if (exported === "default") {
        entry.defaultName = local
      } else {
        entry.named.push(exported === local ? exported : `${exported} as ${local}`)
      }
      byModule.set(specifier, entry)
    }
    return [...byModule]
      .sort(([left], [right]) => compare(left, right))
      .map(([specifier, entry]) => {
        const named = entry.named.length > 0 ? `{ ${entry.named.sort(compare).join(", ")} }` : ""
        const parts = [entry.defaultName, named].filter(Boolean).join(", ")
        return `import ${parts} from ${JSON.stringify(specifier)}`
      })
  }
}

function camelCase(specifier: string): string {
  const last = specifier.split("/").findLast((part) => part !== "." && part !== "..") ?? "module"
  const words = last
    .replace(/\.[^.]+$/, "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
  const name = words
    .map((word, index) => (index === 0 ? word.toLowerCase() : `${word[0]?.toUpperCase() ?? ""}${word.slice(1)}`))
    .join("")
  return identifier.test(name) ? name : `module${name}`
}

function compare(left: string, right: string): number {
  if (left === right) {
    return 0
  }
  return left < right ? -1 : 1
}
